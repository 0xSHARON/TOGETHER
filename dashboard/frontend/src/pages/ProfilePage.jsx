import React, { useState, useEffect } from 'react';
import axios from 'axios';
import { 
  ImageIcon, 
  RefreshCw, 
  Download
} from 'lucide-react';
import { useAuth } from '../context/AuthContext';

export default function ProfilePage() {
  const { user } = useAuth();
  const [profileData, setProfileData] = useState(null);
  const [loading, setLoading] = useState(true);
  const [bannerKey, setBannerKey] = useState(Date.now());
  const [bannerLoading, setBannerLoading] = useState(true);

  useEffect(() => {
    fetchProfile();
  }, []);

  async function fetchProfile() {
    try {
      const resp = await axios.get('/api/auth/profile', { withCredentials: true });
      setProfileData(resp.data);
    } catch (err) {
      console.error('Failed to load profile:', err);
    } finally {
      setLoading(false);
    }
  }

  function handleRefreshBanner() {
    setBannerLoading(true);
    setBannerKey(Date.now());
  }

  if (loading) {
    return (
      <div className="text-center py-24 font-mono text-sm text-brutal-accent animate-pulse">
        [ SYNCHRONIZING DISCORD USER PROFILE TELEMETRY... ]
      </div>
    );
  }

  const u = profileData?.user || user;

  return (
    <div className="space-y-6 max-w-5xl mx-auto pb-12 font-mono">
      {/* ── AUTHENTIC DISCORD CANVAS BANNER (Generated by @napi-rs/canvas) ── */}
      <div className="border-2 border-brutal-border bg-brutal-surface shadow-brutal overflow-hidden">
        {/* Banner Top Toolbar */}
        <div className="bg-black p-3.5 border-b-2 border-brutal-border flex flex-col sm:flex-row items-start sm:items-center justify-between gap-3">
          <div className="flex items-center gap-2.5">
            <ImageIcon className="w-4 h-4 text-brutal-accent shrink-0" />
            <span className="font-mono text-xs font-bold text-white uppercase tracking-wider">
              DISCORD MUSIC PROFILE
            </span>
            <span className="font-mono text-[9px] bg-brutal-accent text-black font-black px-1.5 py-0.5 uppercase">
              1200 × 675
            </span>
            {u?.isOwner && (
              <span className="font-mono text-[9px] bg-red-600 text-white font-black px-1.5 py-0.5 border border-black shadow-brutal-sm uppercase">
                👑 BOT OWNER
              </span>
            )}
          </div>

          <div className="flex flex-wrap items-center gap-2">
            <button
              onClick={handleRefreshBanner}
              className="px-3 py-1.5 bg-zinc-900 border border-zinc-700 hover:border-white text-zinc-300 hover:text-white text-xs font-bold flex items-center gap-1.5 transition-all"
              title="Re-render Discord canvas"
            >
              <RefreshCw className={`w-3.5 h-3.5 ${bannerLoading ? 'animate-spin' : ''}`} />
              <span>REFRESH</span>
            </button>
            <a
              href={`/api/auth/profile-banner?t=${bannerKey}`}
              download={`together_profile_${u?.username || 'user'}.png`}
              target="_blank"
              rel="noreferrer"
              className="px-3 py-1.5 bg-zinc-900 border border-zinc-700 hover:border-white text-zinc-300 hover:text-white text-xs font-bold flex items-center gap-1.5 transition-all"
              title="Download high-res PNG banner"
            >
              <Download className="w-3.5 h-3.5" />
              <span>DOWNLOAD PNG</span>
            </a>
          </div>
        </div>

        {/* High-Resolution Discord Canvas Banner Image */}
        <div className="relative bg-zinc-950 aspect-[1200/675] w-full overflow-hidden flex items-center justify-center">
          <img
            key={bannerKey}
            src={`/api/auth/profile-banner?t=${bannerKey}`}
            alt={`${u?.displayName || u?.username}'s Discord Music Profile`}
            onLoad={() => setBannerLoading(false)}
            onError={() => setBannerLoading(false)}
            className="w-full h-full object-cover block"
          />
          {bannerLoading && (
            <div className="absolute inset-0 bg-black/85 flex items-center justify-center font-mono text-xs text-brutal-accent animate-pulse">
              [ RENDERING AUTHENTIC DISCORD NEO-BRUTALIST CANVAS... ]
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
